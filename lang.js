    const SUPPORTED = ["en", "ru", "fr", "de", "tr"];
    const TARGET_EMAIL = "info@tgstraveluz.com";

    function getSavedLang() {
        const urlParam = new URLSearchParams(window.location.search).get("lang");
        if (urlParam && SUPPORTED.includes(urlParam)) {
            localStorage.setItem("tgs_lang", urlParam);
            return urlParam;
        }
        const saved = localStorage.getItem("tgs_lang");
        return SUPPORTED.includes(saved) ? saved : "en";
    }

    window.tgsLang = getSavedLang();

    window.tgsTranslate = function (key, lang) {
        const l = lang || window.tgsLang || "en";
        const pageDict = (window.PAGE_TRANSLATIONS && window.PAGE_TRANSLATIONS[l]) || {};
        const commonDict = window.TGS_COMMON_TRANSLATIONS[l] || {};
        const fallbackPage = (window.PAGE_TRANSLATIONS && window.PAGE_TRANSLATIONS.en) || {};
        const fallbackCommon = window.TGS_COMMON_TRANSLATIONS.en || {};

        if (pageDict[key] !== undefined) return pageDict[key];
        if (commonDict[key] !== undefined) return commonDict[key];
        if (fallbackPage[key] !== undefined) return fallbackPage[key];
        if (fallbackCommon[key] !== undefined) return fallbackCommon[key];
        return null;
    };

    window.setLanguage = function (lang) {
        if (!SUPPORTED.includes(lang)) lang = "en";
        window.tgsLang = lang;
        localStorage.setItem("tgs_lang", lang);
        document.documentElement.lang = lang;

        document.querySelectorAll("[data-i18n]").forEach((el) => {
            const val = window.tgsTranslate(el.getAttribute("data-i18n"), lang);
            if (val !== null) el.textContent = val;
        });

        document.querySelectorAll("[data-i18n-html]").forEach((el) => {
            const val = window.tgsTranslate(el.getAttribute("data-i18n-html"), lang);
            if (val !== null) el.innerHTML = val;
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
            const val = window.tgsTranslate(el.getAttribute("data-i18n-placeholder"), lang);
            if (val !== null) el.setAttribute("placeholder", val);
        });

        const pageTitle = window.tgsTranslate("page_title", lang);
        if (pageTitle) document.title = pageTitle;

        document.querySelectorAll(".current-lang-label").forEach((el) => {
            el.textContent = lang.toUpperCase();
        });

        document.querySelectorAll("[data-lang-option]").forEach((btn) => {
            const isActive = btn.getAttribute("data-lang-option") === lang;
            btn.classList.toggle("text-gold", isActive);
            btn.classList.toggle("font-bold", isActive);
            btn.classList.toggle("bg-cream/60", isActive);
        });

        document.querySelectorAll(".lang-dropdown-list").forEach((menu) => {
            menu.classList.add("hidden");
        });

        window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
    };

    // ── УНИВЕРСАЛЬНАЯ ОТПРАВКА ФОРМ НА info@tgstraveluz.com ──
    function attachEmailHandler(form) {
        if (!form || form.dataset.tgsBound) return;
        form.dataset.tgsBound = "true";

        form.addEventListener("submit", async function (e) {
            e.preventDefault();

            const submitBtn = form.querySelector('button[type="submit"]');
            let statusEl = form.querySelector(".tgs-form-status");
            if (!statusEl) {
                statusEl = document.createElement("div");
                statusEl.className = "tgs-form-status text-sm mt-3 font-medium";
                form.appendChild(statusEl);
            }

            const originalText = submitBtn ? submitBtn.textContent : "";
            if (submitBtn) {
                submitBtn.disabled = true;
                submitBtn.textContent = window.tgsTranslate("form_sending") || "Sending...";
            }
            statusEl.textContent = "";

            const formData = new FormData(form);
            const payload = {};
            formData.forEach((value, key) => {
                payload[key] = value;
            });
            payload["_subject"] = "New TGS Travel Request (" + document.title + ")";
            payload["_template"] = "table";
            payload["_captcha"] = "false";
            payload["Page"] = window.location.href;
            payload["Language"] = (window.tgsLang || "en").toUpperCase();

            try {
                const res = await fetch("https://formsubmit.co/ajax/" + TARGET_EMAIL, {
                    method: "POST",
                    headers: {
                        "Content-Type": "application/json",
                        "Accept": "application/json"
                    },
                    body: JSON.stringify(payload)
                });
                const data = await res.json();

                if (res.ok && (data.success === "true" || data.success === true)) {
                    statusEl.className = "tgs-form-status text-sm mt-3 font-medium text-emerald-800 bg-emerald-50 border border-emerald-200 rounded-lg px-4 py-3";
                    statusEl.textContent = window.tgsTranslate("form_success");
                    form.reset();
                } else if (data && data.message && data.message.toLowerCase().includes("activation")) {
                    statusEl.className = "tgs-form-status text-sm mt-3 font-medium text-amber-800 bg-amber-50 border border-amber-200 rounded-lg px-4 py-3";
                    statusEl.textContent = "Almost done! Check info@tgstraveluz.com and click 'Activate Form' (one-time setup).";
                } else {
                    throw new Error((data && data.message) || "Submit error");
                }
            } catch (err) {
                statusEl.className = "tgs-form-status text-sm mt-3 font-medium text-red-700 bg-red-50 border border-red-200 rounded-lg px-4 py-3";
                statusEl.textContent = window.tgsTranslate("form_error");
            } finally {
                if (submitBtn) {
                    submitBtn.disabled = false;
                    submitBtn.textContent = originalText;
                }
            }
        });
    }

